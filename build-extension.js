/**
 * Wrap each built filter as a deferred job for the extension's bootstrap, which
 * decides when a diff is on screen. The wrapper's own presence check keeps an
 * automatic install idempotent: the filters themselves treat a second run as a
 * toggle, which is right for a bookmarklet click and wrong here.
 */
const fs = require('fs');
const path = require('path');

const HERE = __dirname;
const OUT_DIR = path.join(HERE, 'extension', 'filters');
// Readable source where there is one: the Chrome Web Store rejects obfuscated
// code and reviewers read what ships. Minification only serves the bookmarklet,
// which has to fit in a URL.
const FILTERS = [
    { source: 'hide-comment-diffs.min.js', global: '__ghCommentFilter' },
    { source: 'hide-test-files.src.js', global: '__ghTestFileFilter' }
];

fs.mkdirSync(OUT_DIR, { recursive: true });
for (const filter of FILTERS) {
    const source = fs.readFileSync(path.join(HERE, filter.source), 'utf8').trim();
    const wrapped = `/* Generated by build-extension.js from ${filter.source} — do not edit. */\n`
        + '(window.__ghDiffFilterQueue = window.__ghDiffFilterQueue || []).push(function () {\n'
        + `    if (window.${filter.global}) { window.${filter.global}.apply(); return; }\n`
        + source + '\n});\n';
    const out = path.join(OUT_DIR, filter.source.replace(/\.(min|src)\.js$/, '.js'));
    fs.writeFileSync(out, wrapped);
    console.log(`${path.relative(HERE, out)}  ${wrapped.length} bytes`);
}
